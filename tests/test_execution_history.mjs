import assert from 'node:assert/strict';
import {ChangeSet, Text} from '@codemirror/state';
import {ExecutionHistory} from '../web/execution-history.mjs';

const history = new ExecutionHistory();
let text = 'import math\nx = math.sqrt(4)\n';
function finish(task) { history.begin(task); history.commit(text); }
function edit(from, to, insert) {
  const changes = ChangeSet.of({from, to, insert}, text.length);
  text = changes.apply(Text.of(text.split('\n'))).toString();
  history.change(changes, text);
}
finish(history.plan(text)[0]);
assert.equal(history.plan(text).length, 0, 'unchanged code must not rerun');
edit(text.length, text.length, 'print(x)\n');
let plan = history.plan(text);
assert.equal(plan.length, 1);
assert.equal(plan[0].source.trim(), 'print(x)', 'appended code becomes one new block');
finish(plan[0]);
assert.equal(history.blocks.length, 2);
const secondId = history.blocks[1].id;
edit(text.indexOf('print(x)'),text.indexOf('print(x)')+8,'print(x + 1)');
plan = history.plan(text);
assert.equal(plan.length, 1, 'editing last block only reruns last block');
assert.equal(plan[0].id, secondId, 'existing output anchor must be reused');
finish(plan[0]);
edit(text.indexOf('sqrt(4)')+5,text.indexOf('sqrt(4)')+6,'9');
plan = history.plan(text);
assert.equal(plan.length, 2, 'editing first block reruns both original blocks');
assert.equal(plan[1].id, secondId);
finish(plan[0]); finish(plan[1]);
assert.equal(history.plan(text).length,0);
const restored = new ExecutionHistory();
restored.restore(history.snapshot(), text);
assert.equal(restored.plan(text).length,0);
const deferred = new ExecutionHistory();
deferred.restore(history.snapshot(), text);
const changedText=text.replace('sqrt(9)','sqrt(16)');
const deferredChange=ChangeSet.of({from:text.indexOf('sqrt(9)')+5,to:text.indexOf('sqrt(9)')+6,insert:'16'},text.length);
deferred.change(deferredChange,changedText);
const deferredTasks=deferred.plan(changedText);
deferred.begin(deferredTasks[0]); deferred.commit(changedText);
assert.equal(deferred.plan(changedText)[0].id,secondId,'downstream work must stay dirty when replay is interrupted after the first block');
edit(text.length,text.length,'print("later")');
plan=history.plan(text);
history.begin(plan[0]); history.fail();
assert.equal(history.plan(text)[0].source.trim(),'print("later")','failure must not advance boundary');
history.begin(history.plan(text)[0]);
edit(text.length,text.length,'\nprint("written while running")');
history.commit(text);
assert.equal(history.plan(text)[0].source.trim(),'print("written while running")');
history.reset();
assert.equal(history.plan(text)[0].from,0,'reset must run imports again');
const boundary = new ExecutionHistory();
let joined = 'a=1\nb=2\n';
boundary.begin({id:'a',from:0,to:3,source:'a=1'}); boundary.commit(joined);
boundary.begin({id:'b',from:3,to:7,source:'\nb=2'}); boundary.commit(joined);
const removal=ChangeSet.of({from:3,to:4,insert:''},joined.length);
joined=removal.apply(Text.of(joined.split('\n'))).toString();
boundary.change(removal,joined);
assert.equal(boundary.plan(joined)[0].source,'a=1b=2','removing a block separator must merge the invalidated contexts');
console.log('PASS: execution block boundaries, dirty dependencies, stable anchors, failure, refresh, append during execution, reset');
